#include <iostream>
#include <windows.h>

using namespace std;

/*
========================================================================================================================================
                                                        БІНАРНЕ ДЕРЕВО ПОШУКУ
========================================================================================================================================

ДЕРЕВО — динамічна структура, в якій кожен вузол може мати кілька дочірніх вузлів. Верхній вузол називається коренем (root),
вузли без дітей — листками.

БІНАРНЕ ДЕРЕВО — кожен вузол має не більше двох дітей: лівого (left) і правого (right).

БІНАРНЕ ДЕРЕВО ПОШУКУ (BST) — бінарне дерево, де для кожного вузла:
  - усі значення в лівому піддереві МЕНШІ за значення вузла;
  - усі значення в правому піддереві БІЛЬШІ або рівні.

                50
              /    \
            30      70
           /  \    /  \
         20   40  60   80

Пошук: на кожному кроці йдемо ліворуч або праворуч і відкидаємо половину дерева — як у бінарному пошуку по масиву.

Майже всі операції з деревом зручно писати РЕКУРСИВНО: кожне піддерево — це теж дерево.

У багатьох мовах програмування вбудовані структури даних для збереження відсортованих унікальних елементів або пар «ключ — значення»
працюють на базі збалансованих бінарних дерев пошуку (наприклад, std::map у C++, TreeMap у Java).

У STL на збалансованих деревах пошуку побудовані:
  std::set      — набір унікальних відсортованих значень (бібліотека <set>);
  std::multiset — те саме, але значення можуть повторюватися (теж <set>);
  std::map      — пари «ключ — значення», відсортовані за ключем, ключі унікальні (бібліотека <map>);
  std::multimap — те саме, але ключі можуть повторюватися (теж <map>).
*/

template <typename T>
class TreeNode
{
public:
    T data;
    TreeNode* left;
    TreeNode* right;

    TreeNode(const T& value) : data(value), left(nullptr), right(nullptr) {}
};

template <typename T>
class Tree
{
private:
    TreeNode<T>* root;

    // Рекурсивне додавання: повертає корінь піддерева після вставки
    TreeNode<T>* insertNode(TreeNode<T>* node, const T& value)
    {
        if (node == nullptr) // базовий випадок: знайшли вільне місце
        {
            return new TreeNode<T>(value);
        }

        if (value < node->data)
        {
            node->left = insertNode(node->left, value);
        }
        else
        {
            node->right = insertNode(node->right, value);
        }
        return node;
    }

    // Обхід «ліве піддерево -> вузол -> праве піддерево» видає значення у відсортованому порядку
    void showNode(TreeNode<T>* node) const
    {
        if (node == nullptr)
        {
            return;
        }
        showNode(node->left);
        cout << node->data << " ";
        showNode(node->right);
    }

    // Знищення: спочатку діти, потім сам вузол
    void destroyNode(TreeNode<T>* node)
    {
        if (node == nullptr)
        {
            return;
        }
        destroyNode(node->left);
        destroyNode(node->right);
        delete node;
    }

public:
    Tree() : root(nullptr) {}

    Tree(const Tree&) = delete;
    Tree& operator=(const Tree&) = delete;

    ~Tree()
    {
        destroyNode(root);
    }

    void insert(const T& value)
    {
        root = insertNode(root, value);
    }

    // Пошук без рекурсії: йдемо ліворуч або праворуч
    bool contains(const T& value) const
    {
        TreeNode<T>* current = root;
        while (current != nullptr)
        {
            if (value == current->data)
            {
                return true;
            }
            current = (value < current->data) ? current->left : current->right;
        }
        return false;
    }

    void show() const
    {
        showNode(root);
        cout << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Рекорди гравців додаються в довільному порядку
    Tree<int> scores;

    int values[] = { 50, 30, 70, 20, 40, 60, 80 };
    for (int value : values)
    {
        scores.insert(value);
    }

    // Обхід дерева видає рекорди вже відсортованими
    cout << "Рекорди за зростанням: ";
    scores.show();

    cout << "Рекорд 60 є? " << (scores.contains(60) ? "так" : "ні") << endl;
    cout << "Рекорд 65 є? " << (scores.contains(65) ? "так" : "ні") << endl;

    return 0;
}

/*
========================================================================================================================================
                                                  ІНСАЙТИ / ЛАЙФХАКИ / BEST PRACTICES
========================================================================================================================================

1. Якщо додавати значення вже відсортованими (10, 20, 30, 40...), дерево «вироджується» у список: усі вузли йдуть праворуч, і пошук
   стає таким самим повільним, як у списку.

2. Цю проблему вирішують збалансовані дерева, наприклад червоно-чорне: після кожної вставки воно саме себе перебудовує.
   Саме на ньому зазвичай побудований std::map (зустрінемо його, коли вивчатимемо STL).

3. Видалення вузла з BST — найскладніша операція (три різні випадки), детальний алгоритм — у практичній роботі.

4. Чому знищення йде «спочатку діти, потім вузол»: якщо видалити вузол першим, покажчики left і right будуть прочитані зі звільненої
   пам'яті.

========================================================================================================================================
                                                         ПРАКТИКА (БОНУС ДО ДЗ)
========================================================================================================================================

Завдання. Видалення вузла з дерева
Допишіть у клас Tree:
  - private-метод TreeNode<T>* removeNode(TreeNode<T>* node, const T& value) — видаляє value з піддерева node
    і повертає корінь цього піддерева після видалення (так само, як insertNode);
  - public-метод void remove(const T& value) — викликає root = removeNode(root, value);

ГОЛОВНА ІДЕЯ. removeNode, як і insertNode, повертає корінь піддерева, а батьківський вузол записує результат у свій left або right:
    node->left = removeNode(node->left, value);
Тому шукати батька вузла, який видаляємо, не потрібно: батько сам «перечепить» свій покажчик на те, що поверне рекурсія.

АЛГОРИТМ removeNode(node, value):

  Крок 1. Якщо node == nullptr — значення в дереві немає. Повертаємо nullptr.

  Крок 2. Шукаємо вузол — так само, як у insertNode:
    - value < node->data  ->  node->left  = removeNode(node->left, value);   повертаємо node;
    - value > node->data  ->  node->right = removeNode(node->right, value);  повертаємо node;
    - інакше вузол знайдено — переходимо до кроку 3.

  Крок 3. Видаляємо знайдений вузол. Є три випадки.

  Випадок А. Вузол без дітей (листок): left == nullptr і right == nullptr.
    - delete node;
    - повертаємо nullptr — у батька на цьому місці стане порожньо.

            50                              50
           /  \          remove(20)        /  \
         30    70        --------->      30    70
        /  \   / \                         \   / \
      20   40 60  80                       40 60  80

  Випадок Б. Вузол з однією дитиною: рівно один з покажчиків left або right дорівнює nullptr.
    - запам'ятовуємо єдину дитину: TreeNode<T>* child = (node->left != nullptr) ? node->left : node->right;
    - delete node;
    - повертаємо child — дитина займає місце видаленого вузла разом з усім своїм піддеревом.

            50                              50
           /  \          remove(30)        /  \
         30    70        --------->      40    70
           \   / \                             / \
           40 60  80                          60  80

  Випадок В. Вузол з двома дітьми.
    Просто видалити такий вузол не можна: у батька для нього лише одне місце, а дітей двоє.
    Тому вузол НЕ видаляємо, а замінюємо його значення на найменше значення з правого піддерева:
    - знаходимо найлівіший вузол правого піддерева (як у min із завдання 1):
          TreeNode<T>* smallest = node->right;
          поки smallest->left != nullptr: smallest = smallest->left;
    - копіюємо його значення у поточний вузол: node->data = smallest->data;
    - тепер це значення є в дереві двічі — видаляємо дублікат з правого піддерева:
          node->right = removeNode(node->right, smallest->data);
    - повертаємо node.

            50                              60
           /  \          remove(50)        /  \
         40    70        --------->      40    70
               / \                               \
              60  80                              80

    Чому саме найменше з правого піддерева: воно більше за всі значення ліворуч і не більше за решту значень праворуч,
    тому правило BST не порушується. А в найлівішого вузла немає лівої дитини, тож його видалення — завжди випадок А або Б,
    і рекурсія не піде по колу.

  Важливо: у випадках А і Б спочатку запам'ятайте те, що треба повернути (nullptr або child), і лише потім робіть delete node.
  Після delete читати node->left і node->right не можна (див. інсайт 4).

У main:
  - побудуйте дерево з прикладу (50, 30, 70, 20, 40, 60, 80) і виведіть його через show();
  - по черзі видаліть 20 (листок), 30 (одна дитина), 50 (корінь з двома дітьми) — після кожного видалення виведіть дерево;
  - перевірте contains для видалених значень;
  - видаліть значення, якого немає в дереві (наприклад, 100): програма не повинна впасти, дерево не змінюється.

Перевірка себе: після всіх видалень show() має вивести 40 60 70 80. Обхід завжди має залишатися відсортованим —
якщо порядок зламався, шукайте помилку у випадку В.
*/
